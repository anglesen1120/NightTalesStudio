using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NightTales.Domain.Communication;
using NightTales.Infrastructure.Persistence.Conventions;

namespace NightTales.Infrastructure.Persistence.Configurations;

/// <summary>
/// The <c>email_messages</c> table (09 README BD9/D9, 09.2.6-T3): one row per queued message, the row the
/// sender records every attempt in and the row <c>IEmailDeliveryStatus</c> reads.
/// </summary>
/// <remarks>
/// <para>
/// <c>locale</c> and <c>status</c> are the D8 enum pair (snake_case text plus the value <c>CHECK</c>), so no
/// other locale and no fourth state can be stored; <c>params</c> is <c>jsonb</c> and carries the allow-listed
/// render values until the message is sent (09 README §B10 WT17); the id is UUIDv7 from the domain factory
/// and is never generated by the database (D3/D8).
/// </para>
/// <para>
/// There is deliberately no foreign key to <c>users</c>: the delivery record outlives the account, and the
/// address itself is not stored at all — only <c>to_hash</c> (13 §5.4, 09 README BD16). The composite
/// <c>(user_id, ...)</c> foreign keys of 09 W3 CR-46 do not apply here, because there is no parent row to
/// point at.
/// </para>
/// </remarks>
internal sealed class EmailMessageConfiguration : IEntityTypeConfiguration<EmailMessage>
{
    public void Configure(EntityTypeBuilder<EmailMessage> builder)
    {
        builder.ToTable("email_messages");
        builder.HasKey(message => message.Id);

        builder.Property(message => message.Id).ValueGeneratedNever();

        builder.Property(message => message.UserId).IsRequired();
        builder.Property(message => message.Template).IsRequired();
        builder.Property(message => message.Locale).HasEnumCheck();
        builder.Property(message => message.ToHash).IsRequired();

        // Plan §3 spells the column `params`, which the snake_case convention cannot derive from
        // `ParamsJson` — and `params` is also a C# keyword, so the property cannot be named that way.
        builder.Property(message => message.ParamsJson).HasColumnName("params").HasColumnType("jsonb");

        builder.Property(message => message.Status).HasEnumCheck();
        builder.Property(message => message.Attempts).HasDefaultValue(0);
        builder.Property(message => message.ProviderMessageId);
        builder.Property(message => message.LastErrorCode);
        builder.Property(message => message.CreatedAt).HasColumnType("timestamptz");
        builder.Property(message => message.SentAt).HasColumnType("timestamptz");

        // The delivery-status read and the operator's view: one user's messages newest first.
        builder.HasIndex(message => new { message.UserId, message.CreatedAt })
            .IsDescending(false, true)
            .HasDatabaseName("ix_email_messages_user_created");
    }
}
