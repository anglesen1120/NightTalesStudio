using System.Net;

namespace NightTales.Infrastructure.Persistence.Entities;

/// <summary>
/// One MFA login challenge (09.3.2-T3 Design, BD1/BD4): the row a password step opens for an account
/// that always signs in with an authenticator, and the second step consumes.
/// </summary>
/// <remarks>
/// <para>
/// Infrastructure-only, like <see cref="RefreshToken"/> next to it: nothing in Application may see the
/// table, and every statement is raw SQL in <c>EfMfaChallengeService</c> — the supersede-then-insert of
/// <c>BeginAsync</c>, the locked read and the two counters of <c>CompleteAsync</c>. They are the same
/// kind of set-based write as the refresh family's, and for the same reason: "at most one completable
/// challenge per account" and "the fifth wrong code kills the challenge" have to be true under
/// concurrency, which a tracked-entity read-modify-write cannot promise.
/// </para>
/// <para>
/// Nothing here is ever stored in plaintext. <see cref="TokenHash"/> and
/// <see cref="PreAuthCookieHash"/> are the SHA-256 hex of the two bearer secrets the login step returns
/// once; the plaintext exists only in the response body and the cookie (BD16).
/// </para>
/// <para>
/// It deliberately does <em>not</em> implement <c>IUserOwned</c>: the login step's caller is anonymous,
/// so the D10 tenant filter would make the resolution by unique <c>token_hash</c> read no row at all.
/// </para>
/// </remarks>
public sealed class AuthChallenge
{
    private AuthChallenge()
    {
    }

    /// <summary>The row id (UUIDv7, generated by the store, never by the database and never by a client).</summary>
    public Guid Id { get; private set; }

    /// <summary>The account that must complete the second step; <c>ON DELETE CASCADE</c> (D9).</summary>
    public Guid UserId { get; private set; }

    /// <summary><c>SHA-256</c> of the <c>mfaToken</c> as lowercase hex — the only stored form.</summary>
    public string TokenHash { get; private set; } = string.Empty;

    /// <summary><c>SHA-256</c> of the pre-auth cookie's value as lowercase hex.</summary>
    public string PreAuthCookieHash { get; private set; } = string.Empty;

    /// <summary>
    /// The <c>User-Agent</c> of the password step, which the completion must repeat (BD4). Null when the
    /// step sent none; an empty submission never matches a stored value.
    /// </summary>
    public string? UserAgent { get; private set; }

    /// <summary>
    /// The address of the password step. It is recorded and <em>never enforced</em>: an IP change
    /// (Wi-Fi → mobile, CGNAT) is audited and the challenge continues (BD4).
    /// </summary>
    public IPAddress? Ip { get; private set; }

    /// <summary>
    /// The wrong codes charged to this challenge. At <c>Auth:Mfa:MaxAttempts</c> the row's
    /// <see cref="UsedAt"/> is set by the same statement, so the row is dead before the next call reads
    /// it.
    /// </summary>
    public short Attempts { get; private set; }

    /// <summary>When the challenge dies: <c>Auth:Mfa:ChallengeMinutes</c> after the password step (BD4: 5).</summary>
    public DateTimeOffset ExpiresAt { get; private set; }

    /// <summary>When it stopped being usable (consumed, superseded or killed by its fifth wrong code).</summary>
    public DateTimeOffset? UsedAt { get; private set; }
}
