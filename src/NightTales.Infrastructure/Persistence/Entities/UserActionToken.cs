using NightTales.Application.Abstractions.Security;
using NightTales.Infrastructure.Persistence.Conventions;

namespace NightTales.Infrastructure.Persistence.Entities;

/// <summary>
/// One single-use action token (09 README BD3/WF11, 09.3.3-T1, table <c>user_action_tokens</c>): the
/// stored SHA-256 of a 32-byte random token, its kind, its expiry and — once spent — its
/// <c>used_at</c> stamp.
/// </summary>
/// <remarks>
/// <para>
/// Infrastructure-only, like <see cref="RefreshToken"/>: nothing in Application may see the table. Every
/// statement that touches it — the invalidating insert, the replay-proof consume — is set-based raw SQL
/// in <c>EfUserActionTokenService</c>, so the table never enters the tracked write model and the
/// "at most one live token per <c>(user, kind, subject)</c>" rule is enforced by a single statement
/// instead of a read-then-write race.
/// </para>
/// <para>
/// It deliberately does <em>not</em> implement <c>IUserOwned</c>: the consume is an anonymous request
/// that has nothing but the presented token, so the D10 tenant filter would make it read no row at all.
/// The reads are keyed by the unique <c>token_hash</c> and the write by the owning user's id.
/// </para>
/// <para>
/// <c>subject_id</c> is the 06 CR-6 / YR8 addition: a subject-scoped flow (06.2.2-T2's publication
/// cancel link) invalidates and consumes per <c>(user, kind, subject)</c>, while a plain flow stores
/// <see langword="null"/> and never touches another flow's subject rows.
/// </para>
/// </remarks>
public sealed class UserActionToken
{
    private UserActionToken()
    {
    }

    /// <summary>The row id (UUIDv7, generated by the issuing statement, never by the database — D3/D8).</summary>
    public Guid Id { get; private set; }

    /// <summary>The user the token authorizes; <c>ON DELETE CASCADE</c>.</summary>
    public Guid UserId { get; private set; }

    /// <summary>The flow the token belongs to; see <see cref="UserActionKind"/>.</summary>
    public UserActionKind Kind { get; private set; }

    /// <summary>The row a subject-scoped flow is about, or <see langword="null"/> for a plain flow.</summary>
    public Guid? SubjectId { get; private set; }

    /// <summary><c>SHA-256</c> of the token as lowercase hex — the only stored form.</summary>
    public string TokenHash { get; private set; } = string.Empty;

    /// <summary>When the row was written, from the issuer's clock.</summary>
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>The instant the token stops being usable.</summary>
    public DateTimeOffset ExpiresAt { get; private set; }

    /// <summary>When the token was spent or invalidated by a newer one, or <see langword="null"/> while live.</summary>
    public DateTimeOffset? UsedAt { get; private set; }
}

/// <summary>
/// The wire spellings of <see cref="UserActionKind"/> (09 README D8/C8): the same snake_case conversion
/// the column's <c>CHECK</c> and the EF converter use, so a raw statement can never store a value the
/// constraint refuses.
/// </summary>
public static class UserActionKinds
{
    /// <summary>The value stored for <paramref name="kind"/>.</summary>
    /// <param name="kind">An action kind.</param>
    public static string ToWire(this UserActionKind kind) => EnumSnakeCase.Convert(kind.ToString());
}
