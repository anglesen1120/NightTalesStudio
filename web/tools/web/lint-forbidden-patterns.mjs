#!/usr/bin/env node
// Scans Angular templates for patterns the TypeScript lint rules cannot express (README D2/D4, task 10.1.2-T1).
// Prints `file:line: <pattern>` per hit and exits 1; exits 0 when clean.
//
// Usage: node tools/web/lint-forbidden-patterns.mjs [dir-or-file ...]   (default: src, relative to web/)
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

const TEMPLATE_SUFFIXES = new Set(['.html', '.htm']);
const SKIPPED_DIRS = new Set(['node_modules', 'dist', '.angular', '.git']);
// Generated by 10.1.4-T1 (D5), excluded from lint like eslint.config.js `ignores`.
const GENERATED = resolve(webRoot, 'src/app/shared/api');

const PATTERNS = [
  { name: '[innerHTML]', regex: /\[(?:attr\.)?inner-?html\b/i },
  { name: 'javascript:', regex: /javascript\s*:/i },
  { name: 'inline on*= handler', regex: /\son[a-z]{3,}\s*=/i },
  { name: 'srcdoc=', regex: /\ssrcdoc\s*=/i },
  { name: '<iframe', regex: /<iframe\b/i },
  { name: 'document.write', regex: /document\s*\.\s*write\b/ },
  { name: 'eval(', regex: /\beval\s*\(/ },
  { name: 'new Function', regex: /\bnew\s+Function\b/ },
];

function isTemplate(file) {
  return TEMPLATE_SUFFIXES.has(extname(file).toLowerCase());
}

function* walk(path) {
  const abs = resolve(path);
  if (abs === GENERATED || abs.startsWith(GENERATED + '/')) {
    return;
  }
  const stat = statSync(abs);
  if (stat.isFile()) {
    if (isTemplate(abs)) {
      yield abs;
    }
    return;
  }
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    if (entry.isDirectory() && SKIPPED_DIRS.has(entry.name)) {
      continue;
    }
    yield* walk(join(abs, entry.name));
  }
}

const targets = process.argv.slice(2);
const roots = (targets.length > 0 ? targets : ['src']).map((target) => resolve(webRoot, target));

let files = 0;
const hits = [];
for (const root of roots) {
  for (const file of walk(root)) {
    files += 1;
    const lines = readFileSync(file, 'utf8').split(/\r?\n/);
    lines.forEach((text, index) => {
      for (const { name, regex } of PATTERNS) {
        if (regex.test(text)) {
          hits.push(`${relative(webRoot, file)}:${index + 1}: ${name}`);
        }
      }
    });
  }
}

if (hits.length > 0) {
  console.error(hits.join('\n'));
  console.error(`lint:forbidden FAIL — ${hits.length} forbidden pattern(s) in ${files} template(s)`);
  process.exit(1);
}
console.log(`lint:forbidden PASS — ${files} template(s) scanned, no forbidden patterns`);
