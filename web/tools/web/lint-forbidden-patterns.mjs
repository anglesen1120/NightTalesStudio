#!/usr/bin/env node
// Scans Angular templates for patterns the TypeScript lint rules cannot express (README D2/D4, task 10.1.2-T1):
// every *.html file, and the inline `template:` strings of every *.ts file.
// Prints `file:line: <pattern>` per hit and exits 1; exits 0 when clean.
//
// Usage: node tools/web/lint-forbidden-patterns.mjs [dir-or-file ...]   (default: src, relative to web/)
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

const TEMPLATE_SUFFIXES = new Set(['.html', '.htm']);
const SCRIPT_SUFFIX = '.ts';
const SKIPPED_DIRS = new Set(['node_modules', 'dist', '.angular', '.git']);
// Generated by 10.1.4-T1 (D5), excluded from lint like eslint.config.js `ignores`.
const GENERATED = resolve(webRoot, 'src/app/shared/api');

// DOM event-handler attribute names (GlobalEventHandlers / window / media / animation events). An allow-list of real
// events keeps custom attributes such as `ongoing=` or `online=` (the event attribute is `ononline`) from matching.
const DOM_EVENTS = [
  'abort', 'afterprint', 'animationcancel', 'animationend', 'animationiteration', 'animationstart', 'auxclick',
  'beforeinput', 'beforeprint', 'beforetoggle', 'beforeunload', 'blur', 'cancel', 'canplay', 'canplaythrough',
  'change', 'click', 'close', 'compositionend', 'compositionstart', 'compositionupdate', 'contextmenu', 'copy',
  'cuechange', 'cut', 'dblclick', 'drag', 'dragend', 'dragenter', 'dragleave', 'dragover', 'dragstart', 'drop',
  'durationchange', 'emptied', 'ended', 'error', 'focus', 'focusin', 'focusout', 'formdata', 'fullscreenchange',
  'fullscreenerror', 'gotpointercapture', 'hashchange', 'input', 'invalid', 'keydown', 'keypress', 'keyup',
  'languagechange', 'load', 'loadeddata', 'loadedmetadata', 'loadstart', 'lostpointercapture', 'message',
  'messageerror', 'mousedown', 'mouseenter', 'mouseleave', 'mousemove', 'mouseout', 'mouseover', 'mouseup',
  'mousewheel', 'offline', 'online', 'pagehide', 'pageshow', 'paste', 'pause', 'play', 'playing', 'pointercancel',
  'pointerdown', 'pointerenter', 'pointerleave', 'pointermove', 'pointerout', 'pointerover', 'pointerrawupdate',
  'pointerup', 'popstate', 'progress', 'ratechange', 'readystatechange', 'rejectionhandled', 'reset', 'resize',
  'scroll', 'scrollend', 'search', 'securitypolicyviolation', 'seeked', 'seeking', 'select', 'selectionchange',
  'selectstart', 'slotchange', 'stalled', 'storage', 'submit', 'suspend', 'timeupdate', 'toggle', 'touchcancel',
  'touchend', 'touchmove', 'touchstart', 'transitioncancel', 'transitionend', 'transitionrun', 'transitionstart',
  'unhandledrejection', 'unload', 'volumechange', 'waiting', 'wheel',
];

// The `on*=` attribute must start a line or follow whitespace, a quote or `/` (`<img/onerror=...>`); Angular's own
// `on-click=` and `(click)=` syntaxes do not match.
const PATTERNS = [
  { name: '[innerHTML]', regex: /(?:\[|\bbind-)(?:attr\.)?inner-?html\b/i },
  { name: 'javascript:', regex: /javascript\s*:/i },
  { name: 'inline on*= handler', regex: new RegExp(`(?:^|[\\s"'/])on(?:${DOM_EVENTS.join('|')})\\s*=`, 'i') },
  { name: 'srcdoc=', regex: /\ssrcdoc\s*=/i },
  { name: '<iframe', regex: /<iframe\b/i },
  { name: 'document.write', regex: /document\s*\.\s*write\b/ },
  { name: 'eval(', regex: /\beval\s*\(/ },
  { name: 'new Function', regex: /\bnew\s+Function\b/ },
];

// `template: \`...\`` / `'...'` / `"..."`; group 1 is the string literal including its quotes.
const INLINE_TEMPLATE = /\btemplate\s*:\s*(`(?:\\[\s\S]|[^`\\])*`|'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*")/g;

function isScannable(file) {
  const extension = extname(file).toLowerCase();
  return TEMPLATE_SUFFIXES.has(extension) || extension === SCRIPT_SUFFIX;
}

function* walk(path) {
  const abs = resolve(path);
  if (abs === GENERATED || abs.startsWith(GENERATED + '/')) {
    return;
  }
  const stat = statSync(abs);
  if (stat.isFile()) {
    if (isScannable(abs)) {
      yield abs;
    }
    return;
  }
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    if (entry.isDirectory() && SKIPPED_DIRS.has(entry.name)) {
      continue;
    }
    yield* walk(join(abs, entry.name));
  }
}

const targets = process.argv.slice(2);
const roots = (targets.length > 0 ? targets : ['src']).map((target) => resolve(webRoot, target));

// Yields `{ firstLine, text }` per template of a file: the whole file for .html, each inline `template:` string
// (first line number inside the .ts file) for .ts.
function* templatesOf(file) {
  const source = readFileSync(file, 'utf8');
  if (extname(file).toLowerCase() !== SCRIPT_SUFFIX) {
    yield { firstLine: 1, text: source };
    return;
  }
  for (const match of source.matchAll(INLINE_TEMPLATE)) {
    const bodyStart = match.index + match[0].length - match[1].length;
    yield { firstLine: source.slice(0, bodyStart).split('\n').length, text: match[1] };
  }
}

let templates = 0;
const hits = [];
for (const root of roots) {
  for (const file of walk(root)) {
    for (const { firstLine, text } of templatesOf(file)) {
      templates += 1;
      text.split(/\r?\n/).forEach((lineText, offset) => {
        for (const { name, regex } of PATTERNS) {
          if (regex.test(lineText)) {
            hits.push(`${relative(webRoot, file)}:${firstLine + offset}: ${name}`);
          }
        }
      });
    }
  }
}

if (hits.length > 0) {
  console.error(hits.join('\n'));
  console.error(`lint:forbidden FAIL — ${hits.length} forbidden pattern(s) in ${templates} template(s)`);
  process.exit(1);
}
console.log(`lint:forbidden PASS — ${templates} template(s) scanned, no forbidden patterns`);
